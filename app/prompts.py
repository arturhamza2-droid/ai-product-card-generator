def build_user_message(product: Product, empty_groups: list[str] | None = None, max_description: int = 6000) -> str:
    payload = product.to_prompt_dict()
    description = payload["description"]
    if isinstance(description, str) and len(description) > max_description:
        payload["description"] = description[:max_description] + " […текст обрезан]"
    groups = "; ".join(empty_groups) if empty_groups else "нет (искать в описании ничего не нужно)"
    return (
        "Входные данные о товаре (JSON):\n"
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + "\n\nЗАДАНИЕ ПО ОПИСАНИЮ. Группы характеристик, по которым в specs данных нет: " + groups
        + ". Просмотри текст description по КАЖДОЙ из этих групп. Если значение есть в description, "
        "обязательно верни его в spec_from_description вместе с дословной цитатой."
    )


def build_retry_message(previous_answer: str, problems: list[str]) -> str:
    bullets = "\n".join(f"- {p}" for p in problems)
    return (
        "В твоём предыдущем ответе найдены нарушения:\n"
        f"{bullets}\n\n"
        "Исправь ТОЛЬКО их и верни полный JSON целиком в том же формате. "
        "Убери любые числа и слова, которых нет во входных данных. "
        "Предыдущий ответ для справки:\n" + previous_answer
    )
